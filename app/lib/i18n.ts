/** Translate an i18n key to display text. Falls back to the key itself when unknown. */
export function t(key: string, lang: string = "zh-CN"): string {
  if (!key) return "";
  const pack = lang.startsWith("en") ? EN : ZH;
  return pack[key] ?? key;
}
